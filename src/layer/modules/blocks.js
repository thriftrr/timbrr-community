import { existsSync, readdirSync, readFileSync } from 'node:fs';
import { basename, join } from 'node:path';
import { addServerHandler, addTemplate, createResolver, defineNuxtModule, extendRouteRules, logger } from '@nuxt/kit';

// Blocks from every layer (docs/manifest.md). Walks the site's layer graph —
// the site itself, any private or community layer, this one — and collects
// each layer's blocks/*.js. Then:
//
//  1. writes #timbrr/blocks, a generated module with every definition and
//     the layer it came from (the renderer, the canvas and the manifest
//     route all read it);
//  2. serves /__timbrr/manifest.json, prerendered so a static deploy has
//     it: how a studio that holds none of this code learns what it can
//     edit here;
//  3. sets up /__timbrr/canvas, the page the studio's builder frames.
//     Client-rendered, and framable by the studio's origin and nothing else.
//
// A layer's tier is `timbrr.tier` in its package.json; anything that
// doesn't say is private.

const BLOCK_FILE = /^[a-z][a-z0-9_]*\.m?js$/;

function readPackage(dir) {
 try {
  return JSON.parse(readFileSync(join(dir, 'package.json'), 'utf8'));
 } catch {
  return {};
 }
}

function collectLayer(dir) {
 const pkg = readPackage(dir);
 const name = pkg.name ?? basename(dir);
 const tier = pkg.timbrr?.tier ?? 'private';
 const blocksDir = join(dir, 'blocks');
 const files = existsSync(blocksDir)
  ? readdirSync(blocksDir)
     .filter((file) => BLOCK_FILE.test(file))
     .sort()
     .map((file) => join(blocksDir, file))
  : [];
 return { name, version: pkg.version ?? '0.0.0', tier, dir, files };
}

export default defineNuxtModule({
 meta: { name: '@timbrr/community/blocks' },

 setup(_options, nuxt) {
  const resolver = createResolver(import.meta.url);

  // Highest priority first (the site), the same order Nuxt resolves
  // everything else in. A layer reached two ways is still one layer.
  const seen = new Set();
  const layers = [];
  for (const layer of nuxt.options._layers) {
   if (seen.has(layer.cwd)) continue;
   seen.add(layer.cwd);
   layers.push(collectLayer(layer.cwd));
  }
  const publicLayers = layers.map(({ name, version, tier }) => ({ name, version, tier }));

  const template = addTemplate({
   filename: 'timbrr/blocks.mjs',
   write: true,
   getContents: () => {
    const imports = [];
    const entries = [];
    layers.forEach((layer, layerIndex) => {
     layer.files.forEach((file, fileIndex) => {
      const id = `block_${layerIndex}_${fileIndex}`;
      imports.push(`import ${id} from ${JSON.stringify(file)};`);
      entries.push(` { def: ${id}, layer: layers[${layerIndex}] },`);
     });
    });
    return [
     "// Generated by @timbrr/community: every layer's blocks/, merged.",
     ...imports,
     `export const layers = ${JSON.stringify(publicLayers)};`,
     'export const definitions = [',
     ...entries,
     '];',
     '',
    ].join('\n');
   },
  });

  nuxt.options.alias['#timbrr/blocks'] = template.dst;
  nuxt.options.alias['#timbrr/define'] = resolver.resolve('../schema/define.js');
  nuxt.options.alias['#timbrr/manifest'] = resolver.resolve('../schema/manifest.js');

  nuxt.hook('nitro:config', (config) => {
   config.alias ||= {};
   config.alias['#timbrr/blocks'] = template.dst;
   config.alias['#timbrr/define'] = resolver.resolve('../schema/define.js');
   config.alias['#timbrr/manifest'] = resolver.resolve('../schema/manifest.js');
   // Nitro leaves files outside the site's own folder to be loaded at run
   // time — a layer from GitHub or npm included — so the generated module
   // and every layer with blocks are bundled in by name.
   config.externals ||= {};
   config.externals.inline ||= [];
   config.externals.inline.push(template.dst, resolver.resolve('..'));
   for (const layer of layers) if (layer.files.length) config.externals.inline.push(layer.dir);
  });

  addServerHandler({ route: '/__timbrr/manifest.json', handler: resolver.resolve('./runtime/manifest.get.js') });
  extendRouteRules('/__timbrr/manifest.json', {
   prerender: true,
   headers: { 'Access-Control-Allow-Origin': '*' },
  });

  // The studio fills the canvas over postMessage, so it's a client-only
  // shell. Who may frame it is decided per request (runtime/canvas-headers.js)
  // from NUXT_PUBLIC_STUDIO_ORIGIN, so a deploy only needs the runtime
  // variable, not a rebuild.
  extendRouteRules('/__timbrr/canvas', { ssr: false });
  addServerHandler({ middleware: true, handler: resolver.resolve('./runtime/canvas-headers.js') });

  const total = layers.reduce((sum, layer) => sum + layer.files.length, 0);
  const from = layers.filter((layer) => layer.files.length).map((layer) => `${layer.name} (${layer.tier}, ${layer.files.length})`);
  logger.info(`[timbrr] ${total} blocks — ${from.join(', ')}`);
 },
});
