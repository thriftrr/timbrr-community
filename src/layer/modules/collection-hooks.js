import { existsSync, readdirSync } from 'node:fs';
import { join } from 'node:path';
import { addImports, addServerImports, addTemplate, createResolver, defineNuxtModule, logger } from '@nuxt/kit';

// Collection hooks from every layer (docs/collection-hooks.md): each layer's
// collection-hooks/*.js, the site's first, gathered into #timbrr/collection-hooks
// (`export const collectionHooks = [...]`) for the app (useCollectionHooks, which
// TbFieldValue draws through) and the site's server (/__timbrr/collection-fields,
// the manifest's collectionHooks flag). defineCollectionHook is auto-imported in
// both, and importable from #timbrr/collection-hook.

const HOOK_FILE = /^[a-z0-9][a-z0-9_-]*\.m?js$/;

// One layer's hook files, sorted, as absolute paths.
export function collectionHookFiles(dir) {
 const folder = join(dir, 'collection-hooks');
 return existsSync(folder)
  ? readdirSync(folder)
     .filter((file) => HOOK_FILE.test(file))
     .sort()
     .map((file) => join(folder, file))
  : [];
}

// The generated module: every file's default export, in order.
export function collectionHooksModule(files) {
 return [
  "// Generated by @timbrr/community: every layer's collection-hooks/, the site's first.",
  ...files.map((file, at) => `import hook_${at} from ${JSON.stringify(file)};`),
  `export const collectionHooks = [${files.map((_, at) => `hook_${at}`).join(', ')}].filter(Boolean);`,
  '',
 ].join('\n');
}

export default defineNuxtModule({
 meta: { name: '@timbrr/community/collection-hooks' },

 setup(_options, nuxt) {
  const resolver = createResolver(import.meta.url);
  const seen = new Set();
  const files = [];
  const dirs = [];
  for (const layer of nuxt.options._layers) {
   if (seen.has(layer.cwd)) continue;
   seen.add(layer.cwd);
   const found = collectionHookFiles(layer.cwd);
   files.push(...found);
   if (found.length) dirs.push(layer.cwd);
  }

  const template = addTemplate({ filename: 'timbrr/collection-hooks.mjs', write: true, getContents: () => collectionHooksModule(files) });
  const define = resolver.resolve('../schema/collection-hooks.js');
  nuxt.options.alias['#timbrr/collection-hooks'] = template.dst;
  nuxt.options.alias['#timbrr/collection-hook'] = define;
  addImports({ name: 'defineCollectionHook', from: define });
  addServerImports([{ name: 'defineCollectionHook', from: define }]);

  nuxt.hook('nitro:config', (config) => {
   config.alias ||= {};
   config.alias['#timbrr/collection-hooks'] = template.dst;
   config.alias['#timbrr/collection-hook'] = define;
   // As the blocks module does: files outside the site's own folder are bundled in by name.
   config.externals ||= {};
   config.externals.inline ||= [];
   config.externals.inline.push(template.dst, define, ...dirs);
  });

  if (files.length) logger.info(`[timbrr] ${files.length} collection hook ${files.length === 1 ? 'file' : 'files'}`);
 },
});
