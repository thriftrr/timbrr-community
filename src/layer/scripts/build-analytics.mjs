// Minifies analytics/a.src.js into server/utils/analytics-script.js, the
// string /__timbrr/a.js serves (docs/analytics.md). The output is committed,
// so a site's build needs nothing extra. With --check it writes nothing and
// fails when the committed file isn't what the source makes (`make check`).
//   node layer/scripts/build-analytics.mjs [--check]
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { transformSync } from 'esbuild';

const root = fileURLToPath(new URL('..', import.meta.url));
const from = `${root}analytics/a.src.js`;
const to = `${root}server/utils/analytics-script.js`;
const { code } = transformSync(readFileSync(from, 'utf8'), { minify: true, target: 'es2018' });
const out = `// Generated by scripts/build-analytics.mjs from analytics/a.src.js. Don't edit.\nexport default ${JSON.stringify(code.trim())};\n`;

if (process.argv.includes('--check')) {
 let have = '';
 try {
  have = readFileSync(to, 'utf8');
 } catch {}
 if (have !== out) {
  console.error('server/utils/analytics-script.js is out of date: run `node layer/scripts/build-analytics.mjs`.');
  process.exit(1);
 }
 console.log('ok  analytics-script.js matches analytics/a.src.js');
} else {
 writeFileSync(to, out);
 console.log(`wrote server/utils/analytics-script.js (${code.length} bytes minified)`);
}
